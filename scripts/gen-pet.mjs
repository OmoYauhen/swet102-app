// Turns assets/pet.svg (the PET drawing, dark ink for a light page) into
// src/screens/pet-svg.ts: recoloured for the dark dashboard, cropped to the
// bike, editor metadata stripped. The battery window keeps a BATTERY_FILL
// placeholder so the ride screen can tint it by charge.
//
//   node scripts/gen-pet.mjs

import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../assets/pet.svg", import.meta.url), "utf8");

// Illustrator class -> fill on the dark theme. Strokes become a cool edge
// light so the silhouette reads against the background.
const FILL = {
  st0: "#4b5563",
  st1: "#1c2229",
  st3: "#262d36",
  st4: "#1c2229",
  st5: "#28303a",
  st7: "#2b2f35",
  st8: "#8b95a3",
  st9: "#6b7280",
  st10: "#4b5563",
  st11: "#1c2229",
  st12: "#262d36",
};
const STROKED = new Set(["st0", "st1", "st2", "st3", "st4", "st5", "st6", "st7", "st8", "st9"]);
const EDGE = "#7b8696";

let body = src
  .replace(/<\?xml[^>]*>/, "")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<sodipodi:namedview[\s\S]*?\/>/, "")
  .replace(/<defs[\s\S]*?<\/defs>/, "")
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  // the battery window, before ids go
  .replace(/class="st10"([^>]*?)id="path107"/, 'fill="BATTERY_FILL" stroke="#0b0e12" stroke-width="2"$1')
  .replace(/\s(?:id|sodipodi:[\w-]+|inkscape:[\w-]+)="[^"]*"/g, "")
  .replace(/style="fill:#666666"/g, 'fill="#8b95a3"')
  .replace(/style="fill:#1a1a1a"/g, 'fill="#14181d"');

// Inline the classes: react-native-svg ignores <style>.
body = body.replace(/class="([^"]+)"/g, (_, cls) => {
  const fill = FILL[cls] ?? "none";
  const stroke = STROKED.has(cls) ? ` stroke="${EDGE}" stroke-width="2"` : "";
  const extra = cls === "st1" || cls === "st2" ? ' stroke-linecap="round"' : "";
  const join = cls === "st2" ? ' stroke-linejoin="round"' : "";
  return `fill="${fill}"${stroke}${extra}${join}`;
});
// An explicit fill attribute written above wins over the class one.
body = body.replace(/fill="[^"]*"((?:\s+[\w-]+="[^"]*")*?)\s+fill="([^"]*)"/g, 'fill="$2"$1');
body = body.replace(/\n\s*\n/g, "\n").replace(/\s+\/>/g, "/>").trim();

const out = `// Generated by scripts/gen-pet.mjs from assets/pet.svg. Do not edit.

/** The bike's crop of the drawing's 2048×2048 canvas. */
export const PET_VIEWBOX = { x: 100, y: 510, w: 1860, h: 1030 };

/** Replace BATTERY_FILL with a colour before rendering. */
export const PET_SVG = \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${PET_VIEWBOX.x} \${PET_VIEWBOX.y} \${PET_VIEWBOX.w} \${PET_VIEWBOX.h}">
${body}
</svg>\`;
`;
writeFileSync(new URL("../src/screens/pet-svg.ts", import.meta.url), out);
console.log(`pet-svg.ts: ${out.length} chars`);
